function validateCatalog() {
  sources.forEach((source) => sourceSchema.parse(source));
  const sourceIds = new Set(sources.map((s) => s.id));
  const groups = [
    [eras, contentSchemas.era],
    [timelineEvents, contentSchemas.timelineEvent],
    [species, contentSchemas.species],
    [cultureTopics, contentSchemas.cultureTopic],
    [behaviorTheories, contentSchemas.behaviorTheory],
    [researchers, contentSchemas.researcher],
    [fossilSites, contentSchemas.fossilSite],
    [migrationRoutes, contentSchemas.migrationRoute],
    [comparisons, contentSchemas.comparisonTopic],
    [simulationEntries, contentSchemas.simulation],
  ] as const;
  for (const [group, schema] of groups) {
    const ids = new Set<string>();
    for (const item of group) {
      schema.parse(item);
      if (ids.has(item.id)) throw new Error(`Duplicate catalog ID: ${item.id}`);
      ids.add(item.id);
      for (const sourceId of item.sourceIds)
        if (!sourceIds.has(sourceId))
          throw new Error(`Missing source ${sourceId} on ${item.id}`);
    }
  }
  const eraIds = new Set(eras.map((item) => item.id));
  const speciesIds = new Set(species.map((item) => item.id));
  for (const event of timelineEvents) {
    if (!eraIds.has(event.eraId))
      throw new Error(`Unknown era ${event.eraId} on ${event.id}`);
  }
  for (const item of [...timelineEvents, ...fossilSites, ...migrationRoutes]) {
    for (const speciesId of item.speciesIds)
      if (!speciesIds.has(speciesId))
        throw new Error(`Unknown species ${speciesId} on ${item.id}`);
  }
}
validateCatalog();
